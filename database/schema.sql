CREATE TABLE IF NOT EXISTS users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     text        NOT NULL CHECK (length(trim(full_name)) BETWEEN 1 AND 100),
  email         text        NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash text        NOT NULL,
  role          text        NOT NULL CHECK (role IN ('student', 'instructor', 'admin')),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auth_tokens (
  token_hash text        PRIMARY KEY,
  user_id    integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role       text        NOT NULL CHECK (role IN ('student', 'instructor', 'admin')),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS auth_tokens_user_idx ON auth_tokens (user_id);

CREATE TABLE IF NOT EXISTS courses (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              text        NOT NULL UNIQUE,
  name              text        NOT NULL,
  first_warning_at  integer     NOT NULL,
  second_warning_at integer     NOT NULL,
  absence_limit     integer     NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (first_warning_at >= 1 AND first_warning_at < second_warning_at AND second_warning_at <= absence_limit)
);

CREATE TABLE IF NOT EXISTS course_members (
  course_id      integer NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  user_id        integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role_in_course text    NOT NULL CHECK (role_in_course IN ('student', 'instructor')),
  PRIMARY KEY (course_id, user_id)
);
CREATE INDEX IF NOT EXISTS course_members_user_idx ON course_members (user_id);

CREATE TABLE IF NOT EXISTS sessions (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  integer     NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  code       text        NOT NULL,
  opened_by  integer     REFERENCES users (id) ON DELETE SET NULL,
  opened_at  timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  closed_at  timestamptz,
  status     text        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  CHECK (expires_at > opened_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS sessions_one_open_per_course ON sessions (course_id) WHERE status = 'open';
CREATE UNIQUE INDEX IF NOT EXISTS sessions_open_code ON sessions (code) WHERE status = 'open';

CREATE TABLE IF NOT EXISTS attendance_records (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id    integer     NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
  student_id    integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  course_id     integer     NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  status        text        NOT NULL CHECK (status IN ('present', 'absent', 'excused')),
  checked_in_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (session_id, student_id)
);
CREATE INDEX IF NOT EXISTS attendance_student_course_idx ON attendance_records (student_id, course_id);

CREATE TABLE IF NOT EXISTS excuse_requests (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendance_record_id integer     NOT NULL UNIQUE REFERENCES attendance_records (id) ON DELETE CASCADE,
  student_id           integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  reason               text        NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 500),
  status               text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  reviewed_by          integer     REFERENCES users (id) ON DELETE SET NULL,
  reviewed_at          timestamptz,
  created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS excuse_requests_status_idx ON excuse_requests (status);

CREATE TABLE IF NOT EXISTS warnings (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id   integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  course_id    integer     NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  level        text        NOT NULL CHECK (level IN ('first_warning', 'second_warning', 'exam_barred')),
  sent_at      timestamptz NOT NULL DEFAULT now(),
  email_result text        NOT NULL,
  UNIQUE (student_id, course_id, level)
);

CREATE TABLE IF NOT EXISTS reports (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  integer     NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  scope      text        NOT NULL CHECK (scope IN ('course', 'student', 'session')),
  format     text        NOT NULL,
  file_key   text        NOT NULL,
  created_by integer     REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
